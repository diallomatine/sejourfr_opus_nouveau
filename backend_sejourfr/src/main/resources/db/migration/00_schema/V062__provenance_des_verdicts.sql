-- ----------------------------------------------------------------------------
-- 2. Le reste des verdicts vient du propriétaire.
-- ----------------------------------------------------------------------------
UPDATE question_notion_suggestions
SET review_source = 'OWNER_REVIEW'
WHERE review_verdict IS NOT NULL AND review_source IS NULL;

-- ----------------------------------------------------------------------------
-- 3. Les tags posés par le seuil : pas de verdict, mais une provenance.
-- On les reconnaît à leur signature — taguée, aucun verdict humain, et une
-- suggestion applicable >= 0,95 qui pointe vers la notion effectivement posée.
-- ----------------------------------------------------------------------------
UPDATE question_notion_suggestions s
SET review_source = 'AUTO_THRESHOLD'
FROM questions q
         JOIN themes t ON t.id = q.theme_id
WHERE q.id = s.question_id
  AND q.civic_notion_id = s.notion_id
  AND s.confidence >= 0.95
  AND s.source_theme_code = t.code
  AND s.review_verdict IS NULL
  AND s.review_source IS NULL
  AND NOT EXISTS (SELECT 1 FROM question_notion_suggestions x
                   WHERE x.question_id = q.id AND x.review_verdict IS NOT NULL);

DROP TABLE agent_v062;

-- ----------------------------------------------------------------------------
-- 🛑 LA CONTRAINTE VIENT APRÈS LE REMPLISSAGE, et pas avant : un verdict sans
-- provenance n'a plus le droit d'exister, mais les 548 déjà en base n'en
-- avaient pas encore quand la colonne est née. La poser d'abord faisait
-- échouer la migration sur sa propre donnée. La réciproque reste fausse —
-- AUTO_THRESHOLD accompagne un tag sans verdict.
-- ----------------------------------------------------------------------------
ALTER TABLE question_notion_suggestions
    ADD CONSTRAINT chk_question_notion_verdict_a_une_source CHECK (
        review_verdict IS NULL OR review_source IS NOT NULL);

-- ----------------------------------------------------------------------------
-- Tout verdict porte-t-il désormais sa provenance ?
-- ----------------------------------------------------------------------------
DO $ctrl$
DECLARE orphelins integer;
BEGIN
    SELECT count(*) INTO orphelins FROM question_notion_suggestions
     WHERE review_verdict IS NOT NULL AND review_source IS NULL;
    IF orphelins > 0 THEN
        RAISE EXCEPTION 'V062 : % verdicts sans provenance.', orphelins;
    END IF;
END $ctrl$;
