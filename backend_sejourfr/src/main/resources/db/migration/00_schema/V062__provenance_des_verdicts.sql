-- ============================================================================
-- V062 — QUI A RENDU CE VERDICT : le propriétaire, un agent, ou un seuil ?
-- ----------------------------------------------------------------------------
-- 🛑 LE DÉFAUT. `review_verdict` disait CE QUI a été décidé, jamais PAR QUI.
-- Or les 157 verdicts de la dernière tranche de relecture (suggestions de
-- confiance 0,90 à 0,94) ont été arbitrés par un agent, sous délégation
-- explicite du propriétaire le 2026-09-11 — pas par le propriétaire lui-même.
-- Ils étaient indistinguables d'une relecture humaine dans les métriques.
--
-- C'est une confusion coûteuse : la précision du modèle se mesure CONTRE une
-- relecture humaine. Y mêler des verdicts rendus par une machine qui lit le
-- même référentiel, c'est mesurer le modèle contre lui-même. Le chiffre monte,
-- et il ne veut plus rien dire.
--
-- Trois provenances, et la requête de mesure honnête devient possible :
--   * OWNER_REVIEW    — le propriétaire a tranché. SEULE référence valable
--                       pour mesurer la précision du modèle.
--   * AGENT_REVIEW    — un agent a arbitré sous délégation, en appliquant les
--                       frontières déjà figées. Décision valide, mesure non.
--   * AUTO_THRESHOLD  — aucun humain n'a rien lu : le tag vient du seuil de
--                       confiance ≥ 0,95 arrêté après l'échantillon de 100.
--                       Ces lignes gardent `review_verdict` NULL.
--
-- ⚠️ AUCUNE NOTION NE CHANGE, AUCUN VERDICT N'EST REFAIT. On ajoute une
-- colonne et on la remplit. Les 157 décisions restent exactement ce qu'elles
-- sont ; elles cessent seulement de se faire passer pour autre chose.
-- ============================================================================

ALTER TABLE question_notion_suggestions
    ADD COLUMN review_source varchar(16);

ALTER TABLE question_notion_suggestions
    ADD CONSTRAINT chk_question_notion_review_source CHECK (
        review_source IS NULL
        OR review_source IN ('OWNER_REVIEW', 'AGENT_REVIEW', 'AUTO_THRESHOLD'));

COMMENT ON COLUMN question_notion_suggestions.review_source IS
    'Qui a decide : OWNER_REVIEW (le proprietaire), AGENT_REVIEW (un agent '
    'sous delegation), AUTO_THRESHOLD (le seuil de confiance, sans relecture). '
    'Pour mesurer la precision du modele contre une VRAIE relecture humaine, '
    'ne retenir que OWNER_REVIEW.';

